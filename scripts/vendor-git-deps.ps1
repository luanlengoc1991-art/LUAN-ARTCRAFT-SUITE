<#
.SYNOPSIS
  Copy every git dependency the apps pin (craft-libs, winprint.rs, filmcraft/pdfcraft crates,
  winit fork, ...) into vendor/git/ and point Cargo at those copies, so building never needs the
  original GitHub repositories.

.DESCRIPTION
  For each app: `cargo vendor --locked` into a temp folder (D:\avt by default, short path), then
  keep only the crates whose Cargo.lock source is `git+...`. Each (repository, rev) gets its own
  directory source, vendor/git/<repo>-<rev12>/, because different apps pin different revs of the
  same crates (same name and version, different code).

  Writes .cargo/config.toml at the repo root. Cargo merges config files from parent directories,
  so this applies to every apps/<id>/ without touching any upstream file. crates.io packages are
  not vendored (crates.io is the shared Rust registry, not the app vendor).

  Run after an upstream sync that changes a pinned rev (scripts\upgrade.ps1 does this).
  Existing vendor/git/<dir> folders are kept; new ones are added.

.EXAMPLE
  scripts\vendor-git-deps.ps1
  scripts\vendor-git-deps.ps1 -Apps effectcraft
#>
param([string[]] $Apps, [string] $Temp = 'D:\avt')
. "$PSScriptRoot\lib\common.ps1"

$Apps = Split-AppList $Apps
if (-not $Apps) { $Apps = Get-AppIds }
if (-not (Test-Command cargo) -and (Test-Path "$env:USERPROFILE\.cargo\bin\cargo.exe")) { $env:PATH = "$env:USERPROFILE\.cargo\bin;$env:PATH" }
$vendorRoot = Join-Path $script:RepoRoot 'vendor\git'
New-Item -ItemType Directory -Force -Path $vendorRoot, $Temp | Out-Null
$configPath = Join-Path $script:RepoRoot '.cargo\config.toml'

# Existing entries survive (an app may not be re-vendored this run).
$sources = [ordered]@{}   # key: "git+URL?rev=X" -> @{ url; refKind; refValue; dir }
if (Test-Path $configPath) {
  $cur = $null
  foreach ($line in Get-Content $configPath) {
    if ($line -match '^\[source\."(git\+[^"]+)"\]') { $cur = @{ key = $Matches[1] } ; continue }
    if ($cur -and $line -match '^(git|rev|branch|tag) = "([^"]+)"') { if ($Matches[1] -eq 'git') { $cur.url = $Matches[2] } else { $cur.refKind = $Matches[1]; $cur.refValue = $Matches[2] } }
    if ($cur -and $line -match '^replace-with = "([^"]+)"') { $cur.name = $Matches[1] }
    if ($line -match '^directory = "vendor/git/([^"]+)"' -and $cur) { $cur.dir = $Matches[1]; $sources[$cur.key] = $cur; $cur = $null }
  }
}

function Get-Slug([string] $Url, [string] $Value) {
  $repo = ($Url.TrimEnd('/') -replace '\.git$', '').Split('/')[-1].ToLower() -replace '[^a-z0-9._-]', '-'
  $v = ($Value -replace '[^A-Za-z0-9]', '')
  if ($v.Length -gt 12) { $v = $v.Substring(0, 12) }
  return "$repo-$v"
}

foreach ($id in $Apps) {
  $a = Get-App $id
  $dir = Get-AppDir $a
  $tmp = Join-Path $Temp $a.id
  Write-Section "$($a.name): cargo vendor"
  if (Test-Path $tmp) { Remove-Item -Recurse -Force $tmp }
  Push-Location $dir
  try {
    $out = & cmd /d /c "cargo vendor --locked --versioned-dirs `"$tmp`" 2>NUL"
    if ($LASTEXITCODE -ne 0) { throw "cargo vendor failed for $($a.id) (exit $LASTEXITCODE)" }
  } finally { Pop-Location }

  # git sources from cargo vendor's printed config
  $gitSources = @()
  $cur = $null
  foreach ($line in $out) {
    if ($line -match '^\[source\."(git\+[^"]+)"\]') { $cur = @{ key = $Matches[1] }; $gitSources += $cur; continue }
    if ($cur -and $line -match '^(git|rev|branch|tag) = "([^"]+)"') { if ($Matches[1] -eq 'git') { $cur.url = $Matches[2] } else { $cur.refKind = $Matches[1]; $cur.refValue = $Matches[2] } }
    if ($line -match '^\[source\.vendored-sources\]') { $cur = $null }
  }
  if ($gitSources.Count -eq 0) { Write-Host '  no git dependencies'; continue }

  # Cargo.lock: which packages come from which git source (source = "git+URL?rev=X#commit")
  $lock = Get-Content -Raw (Join-Path $dir 'Cargo.lock')
  $pkgs = [regex]::Matches($lock, '(?ms)^\[\[package\]\]\s*\nname = "([^"]+)"\s*\nversion = "([^"]+)"\s*\nsource = "(git\+[^"#]+)#[0-9a-f]+"')
  foreach ($g in $gitSources) {
    $slug = Get-Slug $g.url $g.refValue
    $g.dir = $slug
    $g.name = "vg-$slug"
    $dest = Join-Path $vendorRoot $slug
    $count = 0
    foreach ($p in $pkgs) {
      if ($p.Groups[3].Value -ne $g.key) { continue }
      $crate = "$($p.Groups[1].Value)-$($p.Groups[2].Value)"
      $target = Join-Path $dest $crate
      if (-not (Test-Path $target)) {
        New-Item -ItemType Directory -Force -Path $dest | Out-Null
        Copy-Item -Recurse (Join-Path $tmp $crate) $target
      }
      $count++
    }
    if ($count -eq 0) { throw "no packages matched $($g.key) in $($a.id)/Cargo.lock" }
    $sources[$g.key] = $g
    Write-Host ("  {0,-48} {1} crate(s)" -f "vendor/git/$slug", $count)
  }
  Remove-Item -Recurse -Force $tmp
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# GENERATED by scripts/vendor-git-deps.ps1. Do not edit by hand.')
[void]$sb.AppendLine('# Every git dependency the apps pin is built from vendor/git/ in this repo instead of being')
[void]$sb.AppendLine('# fetched from its original GitHub repository. Cargo merges this file with apps/<id>/.cargo/.')
foreach ($k in $sources.Keys) {
  $s = $sources[$k]
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine("[source.`"$k`"]")
  [void]$sb.AppendLine("git = `"$($s.url)`"")
  [void]$sb.AppendLine("$($s.refKind) = `"$($s.refValue)`"")
  [void]$sb.AppendLine("replace-with = `"$($s.name)`"")
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine("[source.`"$($s.name)`"]")
  [void]$sb.AppendLine("directory = `"vendor/git/$($s.dir)`"")
}
New-Item -ItemType Directory -Force -Path (Split-Path $configPath) | Out-Null
[System.IO.File]::WriteAllText($configPath, ($sb.ToString() -replace "`r`n", "`n"), (New-Object System.Text.UTF8Encoding $false))
Write-Section "Wrote .cargo/config.toml ($($sources.Count) git sources)"
